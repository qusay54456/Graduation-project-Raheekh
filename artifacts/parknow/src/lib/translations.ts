type Section = keyof typeof dict.ar;
type Key<S extends Section> = keyof (typeof dict.ar)[S];

export type TranslationKey = {
  [S in Section]: `${S & string}.${Key<S> & string}`;
}[Section];

export function getTranslation(lang: Lang, key: string): string {
  const [section, prop] = key.split(".") as [Section, string];
  const sectionDict = (dict[lang] as any)[section];
  if (!sectionDict || !(prop in sectionDict)) return key;
  return sectionDict[prop];
}

